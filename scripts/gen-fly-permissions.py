#!/usr/bin/env python3
"""Generate the Fly permission rules for HOST's seat from flyctl's own help text.

Every gated command is listed once by its canonical path. Each path segment is expanded
to every alias flyctl reports on that level's `--help` "Aliases:" line, and each spelling
is emitted in 8 forms (fly, flyctl, */fly, */flyctl; bare and with " *").

    scripts/gen-fly-permissions.py            write the JSON
    scripts/gen-fly-permissions.py --check    exit 1 if the installed flyctl's version or
                                              alias sets differ from the committed JSON

Reads help only; nothing is sent to Fly. Runs flyctl with FLY_NO_UPDATE_CHECK=1, because flyctl
self-updates when run, and this check's own calls once upgraded it (2026-10-14). Hidden commands that --help doesn't list are
not covered and fall to the auto-mode reviewer (see prod-command-permissions.md).
"""

import itertools
import json
import os
import subprocess
import sys
from pathlib import Path

OUT = (
    Path(__file__).resolve().parent.parent
    / "docs/internal/operations/fly-permissions-host-2026-10-12.json"
)
FORMS = ["fly", "flyctl", "*/fly", "*/flyctl"]

ALLOW = ["status", "releases", "apps list", "secrets list"]
ASK = [
    "logs",
    "ssh console",
    "ssh issue",
    "ssh sftp",
    "sftp",
    "console",
    "proxy",
    "machine exec",
    "postgres connect",
    "secrets set",
    "secrets unset",
    "tokens create",
]
DENY = [
    "deploy",
    "launch",
    "destroy",
    "apps create",
    "apps destroy",
    "apps move",
    "apps restart",
    *[
        f"machine {v}"
        for v in (
            "api-proxy clone cordon create destroy kill leases place restart run start stop suspend uncordon update"
        ).split()
    ],
    "scale",
    "volumes",
    "certs",
    "ips",
    "image",
    "config",
    *[
        f"postgres {v}"
        for v in (
            "attach backup config create db detach failover import renew-certs restart users"
        ).split()
    ],
    "mpg",
    "redis",
    "storage",
    "consul",
    "extensions",
    "mcp",
    *[f"tokens {v}" for v in "3p attenuate debug list revoke".split()],
    "secrets deploy",
    "secrets import",
    "secrets sync",
    "orgs",
    "auth",
    "wireguard",
    # Deprecated and absent from `fly help`, but still run on v0.4.115 (Pard, 10-12).
    "suspend",
    "resume",
    "move",
]

REMOVE = {
    "ask": ["Bash(fly *)", "Bash(flyctl *)", "Bash(*/fly *)", "Bash(*/flyctl *)"],
    "deny": [
        "Bash(flyctl deploy:*)",
        "Bash(fly deploy:*)",
        "Bash(flyctl secrets set:*)",
        "Bash(flyctl tokens create:*)",
        "Bash(fly secrets set:*)",
        "Bash(fly secrets unset:*)",
        "Bash(flyctl secrets unset:*)",
        "Bash(fly tokens create:*)",
    ],
}
KEEP_DENY = ['Bash(fly ssh console -a piper-morgan -C *" -*)']
FLAG_FIRST_DENY = [f"Bash({f} -*)" for f in FORMS]


def run(args):
    # flyctl updates itself when run. This check's own `fly version` and --help calls upgraded it
    # 0.4.117 -> 0.4.118 on 2026-10-14 20:55, which made the drift it then reported (Pard traced it).
    # FLY_NO_UPDATE_CHECK=1 is meant to stop that; inferred from the name, not yet tested.
    env = {**os.environ, "FLY_NO_UPDATE_CHECK": "1"}
    return subprocess.run(
        ["fly", *args], capture_output=True, text=True, timeout=30, env=env
    ).stdout


def aliases(path):
    """Aliases of the last segment of `path`, from `fly <path> --help`; the segment itself if none."""
    lines = run([*path, "--help"]).splitlines()
    for i, line in enumerate(lines):
        if line.strip() == "Aliases:" and i + 1 < len(lines):
            names = [n.strip() for n in lines[i + 1].split(",") if n.strip()]
            if names:
                return names
    return [path[-1]]


def spellings(cmd):
    segs = cmd.split()
    per_level = [aliases(segs[: i + 1]) for i in range(len(segs))]
    return sorted({" ".join(p) for p in itertools.product(*per_level)}), {cmd: per_level}


def rules(spells):
    return [r for s in spells for f in FORMS for r in (f"Bash({f} {s})", f"Bash({f} {s} *)")]


def build():
    alias_map, cls = {}, {}
    for name, cmds in (("allow", ALLOW), ("ask", ASK), ("deny", DENY)):
        spells = []
        for c in cmds:
            s, m = spellings(c)
            spells += s
            alias_map.update(m)
        cls[name] = sorted(set(spells))
    overlap = (
        (set(cls["allow"]) & set(cls["ask"]))
        | (set(cls["allow"]) & set(cls["deny"]))
        | (set(cls["ask"]) & set(cls["deny"]))
    )
    if overlap:
        sys.exit(f"spelling in two classes: {sorted(overlap)}")
    version = run(["version"]).split("\n")[0].strip()
    return {
        "_about": (
            "Fly permission split for HOST's seat (xian approved 2026-10-12 via Exec 01M4S0KQRM2CEBYPDV6KG9TTG8). "
            "Generated by scripts/gen-fly-permissions.py; do not hand-edit. Merge into the HOST worktree's "
            ".claude/settings.local.json permissions: delete every rule under 'remove', keep 'keep_deny', append 'add'. "
            "Rationale and check: docs/internal/operations/prod-command-permissions.md, section 2026-10-12."
        ),
        "_flag_first_deny": (
            "The four 'fly -*' denies refuse a global flag before the verb (e.g. 'fly -t TOKEN deploy'), which "
            "would otherwise slip past every per-verb rule. Cost: 'fly --version' is refused too."
        ),
        "flyctl_version": version,
        "aliases": alias_map,
        "spellings": cls,
        "remove": REMOVE,
        "keep_deny": KEEP_DENY,
        "add": {
            "allow": rules(cls["allow"]),
            "ask": rules(cls["ask"]),
            "deny": rules(cls["deny"]) + FLAG_FIRST_DENY,
        },
    }


def main():
    args = sys.argv[1:]
    if args and args != ["--check"]:
        # Anything else (--help, a typo) printed counts and rewrote the JSON until 2026-10-14.
        print(__doc__)
        sys.exit(0 if args[0] in ("-h", "--help") else 2)
    doc = build()
    if "--check" in sys.argv:
        old = json.loads(OUT.read_text())
        drift = [k for k in ("flyctl_version", "aliases") if old.get(k) != doc[k]]
        if drift:
            print(
                f"fly-permissions: DRIFT in {drift}: committed {old.get('flyctl_version')!r}, "
                f"installed {doc['flyctl_version']!r}. Regenerate and review."
            )
            sys.exit(1)
        print(f"fly-permissions: OK ({doc['flyctl_version']})")
        return
    OUT.write_text(json.dumps(doc, indent=2) + "\n")
    print({k: len(v) for k, v in doc["add"].items()}, doc["flyctl_version"])


if __name__ == "__main__":
    main()
